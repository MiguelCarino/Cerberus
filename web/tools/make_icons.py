#!/usr/bin/env python3
"""Render the PWA icons for the Cerberus web UI from the Carino mark.

The mark is never redrawn: web/dist/assets/icons/cerberus.svg is a
byte-for-byte copy of ~/Github/Branding/marks/cerberus.svg (the hub gold C
with the Cerberus pictogram, generated by Branding's marks.py). This script
rasterises that SVG with rsvg-convert and composes it with Pillow onto the
Carino page background (--bg #050505):

  icon-192.png, icon-512.png            purpose "any": mark at 84 % of the tile
  icon-maskable-192.png, -512.png       purpose "maskable": mark inside the
                                        central 80 % safe zone (here 64 %)
  apple-touch-icon.png                  180 px, like "any"

Usage:  python3 web/tools/make_icons.py      (from the repo root or anywhere)
Needs:  rsvg-convert (librsvg) and Pillow.
"""

import io
import pathlib
import shutil
import subprocess
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent  # web/
ICONS = ROOT / "dist" / "assets" / "icons"
MARK = ICONS / "cerberus.svg"
BG = (5, 5, 5, 255)  # carino-ui.css --bg

# (file, size, share of the tile the mark spans)
OUTPUTS = [
    ("icon-192.png", 192, 0.84),
    ("icon-512.png", 512, 0.84),
    ("icon-maskable-192.png", 192, 0.64),
    ("icon-maskable-512.png", 512, 0.64),
    ("apple-touch-icon.png", 180, 0.80),
]


def rasterise(svg: pathlib.Path, px: int) -> Image.Image:
    """Render the SVG at px x px (transparent background) via rsvg-convert."""
    exe = shutil.which("rsvg-convert")
    if not exe:
        sys.exit("make_icons: rsvg-convert not found (install librsvg2-tools)")
    out = subprocess.run(
        [exe, "-w", str(px), "-h", str(px), "-f", "png", str(svg)],
        check=True,
        capture_output=True,
    ).stdout
    return Image.open(io.BytesIO(out)).convert("RGBA")


def main() -> None:
    if not MARK.exists():
        sys.exit(f"make_icons: {MARK} missing; copy Branding/marks/cerberus.svg there first")
    for name, size, share in OUTPUTS:
        inner = round(size * share)
        mark = rasterise(MARK, inner)
        tile = Image.new("RGBA", (size, size), BG)
        off = (size - inner) // 2
        tile.alpha_composite(mark, (off, off))
        tile.convert("RGB").save(ICONS / name, "PNG", optimize=True)
        print(f"wrote {ICONS / name} ({size}px)")


if __name__ == "__main__":
    main()
