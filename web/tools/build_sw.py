#!/usr/bin/env python3
"""Write the app-shell list and build hash into web/dist/sw.js.

The service worker precaches SHELL and names its cache after BUILD, so a
changed file means a new cache and the page's "Reload to update" banner.
Run this after changing anything under web/dist (go test ./web fails while
sw.js is stale, with this command in its message):

    python3 web/tools/build_sw.py

The rules are mirrored by TestServiceWorkerBuild in web/embed_test.go:
  - "/" is dist/index.html, "/manifest.webmanifest" the manifest and
    "/carino-clock.js" dist/assets/carino-clock.js (the navbar loads it
    page-relative);
  - every file under dist/assets with an extension in SHELL_EXT is served
    at "/assets/<path>";
  - entries are sorted by URL; BUILD is the first 12 hex digits of the
    SHA-256 over "<url>\\n<sha256 hex of the file>\\n" for each entry.
"""

import hashlib
import pathlib
import re
import sys

DIST = pathlib.Path(__file__).resolve().parent.parent / "dist"
SW = DIST / "sw.js"
SHELL_EXT = {".js", ".mjs", ".css", ".woff2", ".png", ".svg"}
FIXED = {
    "/": "index.html",
    "/manifest.webmanifest": "manifest.webmanifest",
    "/carino-clock.js": "assets/carino-clock.js",
}


def shell_entries():
    entries = dict(FIXED)
    for f in (DIST / "assets").rglob("*"):
        if f.is_file() and f.suffix in SHELL_EXT:
            rel = f.relative_to(DIST).as_posix()
            entries["/" + rel] = rel
    return sorted(entries.items())


def build_hash(entries):
    h = hashlib.sha256()
    for url, rel in entries:
        digest = hashlib.sha256((DIST / rel).read_bytes()).hexdigest()
        h.update(f"{url}\n{digest}\n".encode())
    return h.hexdigest()[:12]


def main():
    entries = shell_entries()
    build = build_hash(entries)
    urls = ",\n  ".join(f"'{u}'" for u, _ in entries)
    block = (
        "// BEGIN BUILD (generated by web/tools/build_sw.py; do not edit by hand)\n"
        f"const BUILD = '{build}';\n"
        f"const SHELL = [\n  {urls},\n];\n"
        "// END BUILD"
    )
    src = SW.read_text()
    new, n = re.subn(r"// BEGIN BUILD.*?// END BUILD", lambda _: block, src, flags=re.S)
    if n != 1:
        sys.exit("build_sw: BEGIN/END BUILD markers not found in sw.js")
    if new != src:
        SW.write_text(new)
    print(f"sw.js: BUILD {build}, {len(entries)} shell files")


if __name__ == "__main__":
    main()
